import streamlit as st
import pandas as pd
import joblib

# Load the trained model
model = joblib.load("car_price_model.pkl")

# Configure the website
st.set_page_config(
    page_title="Car Price Prediction",
    page_icon="🚗",
    layout="centered"
)

# Website heading
st.title("🚗 Car Price Prediction")
st.write(
    "Enter your car details below to estimate its selling price."
)

st.divider()

# Car details form
with st.form("car_prediction_form"):

    st.subheader("Car Information")

    brand = st.selectbox(
        "Car Brand",
        [
            "Maruti",
            "Hyundai",
            "Tata",
            "Honda",
            "Toyota",
            "Ford",
            "Mahindra",
            "Kia",
            "Renault",
            "Volkswagen",
            "Other"
        ]
    )

    vehicle_age = st.number_input(
        "Vehicle Age (years)",
        min_value=0,
        max_value=40,
        value=5
    )

    km_driven = st.number_input(
        "Kilometres Driven",
        min_value=0,
        value=40000,
        step=1000
    )

    seller_type = st.selectbox(
        "Seller Type",
        ["Individual", "Dealer", "Trustmark Dealer"]
    )

    fuel_type = st.selectbox(
        "Fuel Type",
        ["Petrol", "Diesel", "CNG", "LPG", "Electric"]
    )

    transmission_type = st.selectbox(
        "Transmission",
        ["Manual", "Automatic"]
    )

    mileage = st.number_input(
        "Mileage (km/l or dataset's equivalent unit)",
        min_value=0.0,
        value=20.0,
        step=0.5
    )

    engine = st.number_input(
        "Engine Capacity (cc)",
        min_value=0,
        value=1197,
        step=100
    )

    max_power = st.number_input(
        "Maximum Power (bhp)",
        min_value=0.0,
        value=82.0,
        step=5.0
    )

    seats = st.selectbox(
        "Number of Seats",
        [2, 4, 5, 6, 7, 8, 9, 10]
    )

    submitted = st.form_submit_button(
        "Predict Car Price 🚀"
    )

# Generate prediction
if submitted:

    car = pd.DataFrame([
        {
            "brand": brand,
            "vehicle_age": vehicle_age,
            "km_driven": km_driven,
            "seller_type": seller_type,
            "fuel_type": fuel_type,
            "transmission_type": transmission_type,
            "mileage": mileage,
            "engine": engine,
            "max_power": max_power,
            "seats": seats
        }
    ])

    predicted_price = model.predict(car)[0]

    st.divider()

    st.subheader("Estimated Selling Price")

    st.success(
        f"₹{predicted_price:,.0f}"
    )

    st.caption(
        "This is an estimated price generated by a "
        "machine learning model, not a guaranteed market value."
    )
